# ---------------- Step 0: Import Libraries ----------------
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                              f1_score, classification_report, confusion_matrix)

sns.set_style("whitegrid")
plt.rcParams["figure.figsize"] = (8, 5)

print("✅ Libraries imported successfully")


# ---------------- Step 1: Dataset ----------------
# Using a rule-based synthetic dataset so this runs with no file upload needed.
# To use the real Kaggle dataset instead, replace this whole block with:
# df = pd.read_csv("Fertilizer Prediction.csv")

np.random.seed(42)
n_samples = 1000

soil_types = ["Sandy", "Loamy", "Black", "Red", "Clayey"]
crop_types = ["Rice", "Wheat", "Sugarcane", "Cotton", "Maize", "Millets", "Pulses"]

data = {
    "Temperature": np.random.randint(20, 45, n_samples),
    "Humidity": np.random.randint(30, 90, n_samples),
    "Moisture": np.random.randint(20, 70, n_samples),
    "Soil_Type": np.random.choice(soil_types, n_samples),
    "Crop_Type": np.random.choice(crop_types, n_samples),
    "Nitrogen": np.random.randint(0, 45, n_samples),
    "Potassium": np.random.randint(0, 45, n_samples),
    "Phosphorous": np.random.randint(0, 45, n_samples),
}
df = pd.DataFrame(data)

def assign_fertilizer(row):
    n, p, k = row["Nitrogen"], row["Phosphorous"], row["Potassium"]
    if n < 15 and p < 15 and k < 15:
        return "10-26-26"
    elif n < 15 and p >= 15:
        return "DAP"
    elif n >= 30 and p < 15 and k < 15:
        return "Urea"
    elif n >= 20 and p >= 20 and k >= 20:
        return "17-17-17"
    elif k >= 30 and p < 20:
        return "14-35-14"
    elif n >= 20 and k >= 20:
        return "20-20"
    else:
        return "28-28"

df["Fertilizer_Name"] = df.apply(assign_fertilizer, axis=1)

# add 5% label noise so it's a realistic (not trivially perfect) ML task
noise_idx = df.sample(frac=0.05, random_state=1).index
df.loc[noise_idx, "Fertilizer_Name"] = np.random.choice(
    df["Fertilizer_Name"].unique(), size=len(noise_idx)
)

print("Dataset shape:", df.shape)
df.head(10)


# ---------------- Step 2: Exploratory Data Analysis ----------------
print("----- Data Info -----")
df.info()

print("\n----- Missing Values -----")
print(df.isnull().sum())

print("\n----- Statistical Summary -----")
print(df.describe())

plt.figure(figsize=(9, 5))
sns.countplot(data=df, x="Fertilizer_Name",
              order=df["Fertilizer_Name"].value_counts().index, palette="crest")
plt.title("Class Distribution — Fertilizer Recommendations", fontsize=13, fontweight="bold")
plt.xlabel("Fertilizer")
plt.ylabel("Count")
plt.xticks(rotation=30)
plt.tight_layout()
plt.show()

plt.figure(figsize=(7, 5))
numeric_cols = ["Temperature", "Humidity", "Moisture", "Nitrogen", "Potassium", "Phosphorous"]
sns.heatmap(df[numeric_cols].corr(), annot=True, cmap="Greens", fmt=".2f")
plt.title("Correlation Between Numeric Features", fontsize=13, fontweight="bold")
plt.tight_layout()
plt.show()


# ---------------- Step 3: Data Preprocessing ----------------
df_processed = df.copy()

le_soil = LabelEncoder()
le_crop = LabelEncoder()
le_fert = LabelEncoder()

df_processed["Soil_Type"] = le_soil.fit_transform(df_processed["Soil_Type"])
df_processed["Crop_Type"] = le_crop.fit_transform(df_processed["Crop_Type"])
df_processed["Fertilizer_Name"] = le_fert.fit_transform(df_processed["Fertilizer_Name"])

print("Soil Type mapping   :", dict(zip(le_soil.classes_, le_soil.transform(le_soil.classes_))))
print("Crop Type mapping   :", dict(zip(le_crop.classes_, le_crop.transform(le_crop.classes_))))
print("Fertilizer mapping  :", dict(zip(le_fert.classes_, le_fert.transform(le_fert.classes_))))

X = df_processed.drop("Fertilizer_Name", axis=1)
y = df_processed["Fertilizer_Name"]
feature_cols = X.columns.tolist()

scaler = StandardScaler()
X_scaled = pd.DataFrame(scaler.fit_transform(X), columns=feature_cols)

print("\nBefore scaling:")
print(X.head(3))
print("\nAfter scaling:")
print(X_scaled.head(3))


# ---------------- Step 4: Train-Test Split ----------------
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y, test_size=0.2, random_state=42, stratify=y
)

print("Training samples:", X_train.shape[0])
print("Testing samples :", X_test.shape[0])


# ---------------- Step 5: Train Multiple Classifiers ----------------
models = {
    "Logistic Regression": LogisticRegression(max_iter=1000, random_state=42),
    "Decision Tree": DecisionTreeClassifier(max_depth=8, random_state=42),
    "Random Forest": RandomForestClassifier(n_estimators=200, max_depth=10, random_state=42),
}

results = []
trained_models = {}

for name, model in models.items():
    model.fit(X_train, y_train)
    y_pred = model.predict(X_test)

    acc = accuracy_score(y_test, y_pred)
    prec = precision_score(y_test, y_pred, average="weighted", zero_division=0)
    rec = recall_score(y_test, y_pred, average="weighted", zero_division=0)
    f1 = f1_score(y_test, y_pred, average="weighted", zero_division=0)

    results.append({"Model": name, "Accuracy": acc, "Precision": prec,
                     "Recall": rec, "F1-Score": f1})
    trained_models[name] = model

    print(f"\n===== {name} =====")
    print(f"Accuracy : {acc:.3f}")
    print(f"Precision: {prec:.3f}")
    print(f"Recall   : {rec:.3f}")
    print(f"F1-Score : {f1:.3f}")

results_df = pd.DataFrame(results).sort_values("Accuracy", ascending=False).reset_index(drop=True)
print("\n", results_df)


# ---------------- Step 6: Compare Models ----------------
plt.figure(figsize=(8, 5))
bars = plt.bar(results_df["Model"], results_df["Accuracy"],
                color=["#2C5F2D", "#97BC62", "#E8A33D"])
plt.ylim(0, 1)
plt.ylabel("Accuracy")
plt.title("Model Comparison — Accuracy", fontsize=13, fontweight="bold")
for bar, acc in zip(bars, results_df["Accuracy"]):
    plt.text(bar.get_x() + bar.get_width()/2, acc + 0.02, f"{acc:.2f}",
              ha="center", fontweight="bold")
plt.tight_layout()
plt.show()

best_model_name = results_df.iloc[0]["Model"]
best_model = trained_models[best_model_name]
print(f"🏆 Best performing model: {best_model_name}")


# ---------------- Step 7: Confusion Matrix ----------------
y_pred_best = best_model.predict(X_test)
cm = confusion_matrix(y_test, y_pred_best)

plt.figure(figsize=(8, 6))
sns.heatmap(cm, annot=True, fmt="d", cmap="Greens",
            xticklabels=le_fert.classes_, yticklabels=le_fert.classes_)
plt.title(f"Confusion Matrix — {best_model_name}", fontsize=13, fontweight="bold")
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.tight_layout()
plt.show()

print(classification_report(y_test, y_pred_best, target_names=le_fert.classes_, zero_division=0))


# ---------------- Step 8: Feature Importance ----------------
if hasattr(best_model, "feature_importances_"):
    importances = pd.Series(best_model.feature_importances_, index=feature_cols)
    importances = importances.sort_values(ascending=True)

    plt.figure(figsize=(8, 5))
    importances.plot(kind="barh", color="#2C5F2D")
    plt.title(f"Feature Importance — {best_model_name}", fontsize=13, fontweight="bold")
    plt.xlabel("Importance")
    plt.tight_layout()
    plt.show()
else:
    print(f"{best_model_name} does not directly expose feature importances.")


# ---------------- Step 9: Live Prediction Demo ----------------
def recommend_fertilizer(temperature, humidity, moisture, soil_type, crop_type,
                          nitrogen, potassium, phosphorous):
    """Takes raw soil/crop inputs and returns the recommended fertilizer name."""
    soil_encoded = le_soil.transform([soil_type])[0]
    crop_encoded = le_crop.transform([crop_type])[0]

    input_df = pd.DataFrame([{
        "Temperature": temperature,
        "Humidity": humidity,
        "Moisture": moisture,
        "Soil_Type": soil_encoded,
        "Crop_Type": crop_encoded,
        "Nitrogen": nitrogen,
        "Potassium": potassium,
        "Phosphorous": phosphorous,
    }])[feature_cols]

    input_scaled = scaler.transform(input_df)
    pred_encoded = best_model.predict(input_scaled)[0]
    pred_label = le_fert.inverse_transform([pred_encoded])[0]
    return pred_label


